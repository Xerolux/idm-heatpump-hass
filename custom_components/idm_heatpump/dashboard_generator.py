"""Plant dashboard generation from the live entity registry.

Home Assistant offers no API through which an integration could create or
edit a dashboard, so the integration cannot ship a "generate dashboard"
button that changes the UI.  What it *can* do — and what this module does —
is compose a ready-to-use Lovelace dashboard for the user's actual plant:
real entity IDs from the entity registry (user renames included), only the
heating circuits the entry actually serves, and cards only for entities that
exist.  The ``generate_dashboard`` service returns the dashboard as a
structured response plus a YAML dump to paste or to register as a YAML-mode
dashboard file.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from typing import Any

from .entity import build_entity_unique_id

#: Registry lookup: ``(entity_key, domain) -> entity_id or None``.
type EntityLookup = Callable[[str, str], str | None]

_OVERVIEW_SENSOR_KEYS: tuple[tuple[str, str], ...] = (
    ("outdoor_temp", "sensor"),
    ("hp_flow_temp", "sensor"),
    ("hp_return_temp", "sensor"),
    ("hp_operating_mode", "sensor"),
    ("power_consumption_hp", "sensor"),
    ("calculated_cop", "sensor"),
    ("dhw_temp_top", "sensor"),
)

_ENERGY_SENSOR_KEYS: tuple[str, ...] = (
    "energy_electrical_total",
    "energy_thermal_total",
    "energy_cop_total",
    "energy_co2_total",
)

_DIAGNOSTIC_KEYS: tuple[tuple[str, str], ...] = (
    ("connection_mode", "sensor"),
    ("web_last_success", "sensor"),
    ("connection_reload", "button"),
    ("acknowledge_errors", "button"),
)

_HOT_WATER_BUTTON_KEYS: tuple[str, ...] = ("dhw_boost_start", "dhw_boost_cancel")

_HISTORY_KEYS: tuple[str, str] = ("hp_flow_temp", "calculated_cop")


class PlantDashboardBuilder:
    """Compose the plant dashboard for one config entry from registry IDs."""

    def __init__(self, entry_id: str, lookup: EntityLookup, circuits: Sequence[str]) -> None:
        """Store the entry identity, the registry lookup and the circuits."""
        self._entry_id = entry_id
        self._lookup = lookup
        self._circuits = [str(circuit).lower() for circuit in circuits if str(circuit)]

    def entity(self, key: str, domain: str = "sensor") -> str | None:
        """Return the registry entity ID for an integration entity key."""
        return self._lookup(build_entity_unique_id(self._entry_id, key), domain)

    def _entities_card(self, entities: Sequence[str | None], title: str | None = None) -> dict[str, Any] | None:
        """Build an entities card, or None when every entity is missing."""
        existing = [entity for entity in entities if entity]
        if not existing:
            return None
        card: dict[str, Any] = {"type": "entities", "entities": existing}
        if title:
            card["title"] = title
        return card

    def overview_view(self) -> dict[str, Any] | None:
        """Compose the overview view."""
        cards: list[dict[str, Any]] = [
            {
                "type": "markdown",
                "content": (
                    "# IDM heat pump\nGenerated by the `idm_heatpump.generate_dashboard` "
                    "service from your current entities. Register the YAML as a "
                    "dashboard (``lovelace`` in configuration.yaml) or copy single "
                    "views into an existing dashboard."
                ),
            }
        ]
        if card := self._entities_card(
            [self.entity(key, domain) for key, domain in _OVERVIEW_SENSOR_KEYS],
            "Plant",
        ):
            cards.append(card)
        history = [entity for entity in (self.entity(key) for key in _HISTORY_KEYS) if entity]
        if history:
            cards.append({"type": "history-graph", "entities": history, "hours_to_show": 48, "title": "Trend"})
        if len(cards) > 1:
            return {"title": "Overview", "path": "idm-overview", "cards": cards}
        return None

    def heating_view(self) -> dict[str, Any] | None:
        """Compose one thermostat card plus sensor rows per active circuit."""
        cards: list[dict[str, Any]] = []
        for circuit in self._circuits:
            climate = self.entity(f"climate_hc_{circuit}", "climate") or self.entity(
                f"web_climate_hc_{circuit}", "climate"
            )
            sensors = [
                self.entity(f"hc_{circuit}_flow_temp"),
                self.entity(f"hc_{circuit}_room_temp"),
            ]
            if climate:
                cards.append({"type": "thermostat", "entity": climate})
            if card := self._entities_card(sensors, f"Heating circuit {circuit.upper()}"):
                cards.append(card)
        if cards:
            return {"title": "Heating", "path": "idm-heating", "cards": cards}
        return None

    def hot_water_view(self) -> dict[str, Any] | None:
        """Compose the hot-water view (register or web entity, boost buttons)."""
        water_heater = self.entity("water_heater", "water_heater") or self.entity("web_water_heater", "water_heater")
        cards: list[dict[str, Any]] = []
        if water_heater:
            cards.append({"type": "entities", "entities": [water_heater]})
        entities = [self.entity("dhw_temp_top")] + [self.entity(key, "button") for key in _HOT_WATER_BUTTON_KEYS]
        if card := self._entities_card(entities, "Hot water"):
            cards.append(card)
        if cards:
            return {"title": "Hot water", "path": "idm-hot-water", "cards": cards}
        return None

    def energy_view(self) -> dict[str, Any] | None:
        """Compose the persistent energy totals and the COP trend."""
        cards: list[dict[str, Any]] = []
        if card := self._entities_card([self.entity(key) for key in _ENERGY_SENSOR_KEYS], "Energy totals"):
            cards.append(card)
        if cop := self.entity("energy_cop_total"):
            cards.append({"type": "history-graph", "entities": [cop], "hours_to_show": 336, "title": "COP (14 d)"})
        if cards:
            return {"title": "Energy", "path": "idm-energy", "cards": cards}
        return None

    def diagnostics_view(self) -> dict[str, Any] | None:
        """Compose the connection diagnostics view."""
        card = self._entities_card([self.entity(key, domain) for key, domain in _DIAGNOSTIC_KEYS], "Diagnostics")
        if card is None:
            return None
        return {"title": "Diagnostics", "path": "idm-diagnostics", "cards": [card]}

    def build(self) -> dict[str, Any]:
        """Return the complete dashboard, skipping views without entities."""
        views = [
            view
            for view in (
                self.overview_view(),
                self.heating_view(),
                self.hot_water_view(),
                self.energy_view(),
                self.diagnostics_view(),
            )
            if view is not None
        ]
        return {"title": "IDM Heatpump", "views": views}


def build_plant_dashboard(
    entry_id: str,
    lookup: EntityLookup,
    circuits: Sequence[str],
) -> dict[str, Any]:
    """Compose the plant dashboard; raises ValueError when nothing exists."""
    dashboard = PlantDashboardBuilder(entry_id, lookup, circuits).build()
    if not dashboard["views"]:
        raise ValueError("No dashboard entities found for this entry")
    return dashboard


__all__ = ["EntityLookup", "PlantDashboardBuilder", "build_plant_dashboard"]
